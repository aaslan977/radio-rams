import type { TiksOptions } from '@rexa-developer/tiks'

// Настройки звука интерфейса живут одним объектом на всё приложение, и это не
// вкусовщина, а свойство библиотеки: useTiks заводит на компонент свой объект,
// но тот хранит только тему — звук играет модульный синглтон, и мастер-гейн у
// него один на всех. Два разных значения в двух компонентах не сосуществуют:
// побеждает то, что проинициализировалось последним, то есть громкость молча
// зависела бы от порядка монтирования.
//
// volume задан явно, хотя 0.3 — и есть текущий дефолт библиотеки: уровень
// звука не должен меняться сам собой от обновления зависимости.
//
// Амплитуда каждого звука зашита константой в его генераторе (у щелчка — 0.9)
// и темой не регулируется, поэтому развести громкость диска и кнопки по
// отдельности через эти настройки нельзя. Разный характер звучания достижим
// только разными темами — тема как раз на каждый экземпляр своя.
export const UI_SOUND: TiksOptions = {
  theme: 'soft',
  volume: 0.3,
}
